"""Packs assets/shark.glb and assets/gull.glb into src/77_creatures_data.js as base64 strings."""
import base64, sys
out = sys.argv[1] if len(sys.argv) > 1 else 'src/77_creatures_data.js'
parts = []
for key, path in [('shark', 'assets/shark.glb'), ('gull', 'assets/gull.glb')]:
    parts.append("  %s: '%s'" % (key, base64.b64encode(open(path, 'rb').read()).decode()))
open(out, 'w').write('// Generated by tools/embed_creatures.py from the uploaded models (shark: water hazard, gull: sky ambience).\nconst CREATURE_GLB = {\n' + ',\n'.join(parts) + '\n};\n')
print('wrote', out)
