"""Shrinks assets/character_full.glb to the animations the game uses -> assets/character.glb,
then embeds it as base64 in src/77b_character_data.js. Root-motion position tracks on 'root' are dropped."""
import struct, json, base64, sys
KEEP = ['Idle_A', 'Walk', 'Jog', 'Sprint', 'Jump_air', 'Flying_Forward', 'Glide', 'Swim_Fwd', 'Swim_Idle',
        'Pistol_Idle', 'Pistol_Shoot', 'Pistol_Reload', 'Chop_Tree', 'Consume', 'ClimbUp_1m_RM', 'Death_A',
        'Dance_Body_Roll', 'Dance_Charleston', 'Dance_Simple', 'Jumping_Jacks', 'Greeting', 'Victory']
d = open('assets/character_full.glb', 'rb').read(); off = 12; ch = []
while off < len(d):
    clen, ct = struct.unpack('<I4s', d[off:off + 8]); ch.append(d[off + 8:off + 8 + clen]); off += 8 + clen
J = json.loads(ch[0]); BIN = ch[1]
names = {i: n.get('name', '') for i, n in enumerate(J['nodes'])}
anims = []
for a in J['animations']:
    if a['name'] not in KEEP: continue
    chans = [c for c in a['channels'] if not (names.get(c['target'].get('node')) == 'root' and c['target']['path'] == 'translation')]
    used = sorted({c['sampler'] for c in chans}); remap = {o: n for n, o in enumerate(used)}
    anims.append({'name': a['name'], 'samplers': [a['samplers'][i] for i in used], 'channels': [dict(c, sampler=remap[c['sampler']]) for c in chans]})
J['animations'] = anims
# collect accessors still referenced
acc = set()
for m in J['meshes']:
    for p in m['primitives']:
        acc.update(p['attributes'].values())
        if 'indices' in p: acc.add(p['indices'])
for s in J.get('skins', []):
    if 'inverseBindMatrices' in s: acc.add(s['inverseBindMatrices'])
for a in J['animations']:
    for s in a['samplers']: acc.update([s['input'], s['output']])
views = {J['accessors'][i]['bufferView'] for i in acc if 'bufferView' in J['accessors'][i]}
views.update(im['bufferView'] for im in J.get('images', []) if 'bufferView' in im)
# rebuild buffer
newbin = bytearray(); vmap = {}; newviews = []
for vi in sorted(views):
    v = J['bufferViews'][vi]; start = v.get('byteOffset', 0); data = BIN[start:start + v['byteLength']]
    while len(newbin) % 4: newbin.append(0)
    nv = dict(v); nv['byteOffset'] = len(newbin); nv['buffer'] = 0; vmap[vi] = len(newviews); newviews.append(nv); newbin += data
amap = {}; newacc = []
for ai in sorted(acc):
    a = dict(J['accessors'][ai]); a['bufferView'] = vmap[a['bufferView']]; amap[ai] = len(newacc); newacc.append(a)
for m in J['meshes']:
    for p in m['primitives']:
        p['attributes'] = {k: amap[v] for k, v in p['attributes'].items()}
        if 'indices' in p: p['indices'] = amap[p['indices']]
for s in J.get('skins', []):
    if 'inverseBindMatrices' in s: s['inverseBindMatrices'] = amap[s['inverseBindMatrices']]
for a in J['animations']:
    for s in a['samplers']: s['input'] = amap[s['input']]; s['output'] = amap[s['output']]
for im in J.get('images', []):
    if 'bufferView' in im: im['bufferView'] = vmap[im['bufferView']]
J['accessors'] = newacc; J['bufferViews'] = newviews; J['buffers'] = [{'byteLength': len(newbin)}]
js = json.dumps(J, separators=(',', ':')).encode()
while len(js) % 4: js += b' '
while len(newbin) % 4: newbin.append(0)
glb = struct.pack('<4sII', b'glTF', 2, 12 + 8 + len(js) + 8 + len(newbin)) + struct.pack('<I4s', len(js), b'JSON') + js + struct.pack('<I4s', len(newbin), b'BIN\x00') + bytes(newbin)
open('assets/character.glb', 'wb').write(glb)
open('src/77b_character_data.js', 'w').write('// Generated by tools/compact_char.py from the uploaded character model (animations trimmed to what the game uses).\nconst CHARACTER_GLB = \'' + base64.b64encode(glb).decode() + '\';\n')
print('kept', len(anims), 'animations; glb', len(glb), 'bytes; missing', [k for k in KEEP if k not in [a['name'] for a in anims]])
